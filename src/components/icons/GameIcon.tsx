export type IconName = keyof typeof GAME_ICONS

/** Sized in em so it drops into any spot an emoji used to occupy. */
export function GameIcon({
  name,
  className,
  style,
  strokeWidth = 2.25,
}: {
  name: IconName
  className?: string
  style?: CSSProperties
  strokeWidth?: number
}) {
  const Icon = GAME_ICONS[name]
  return (
    <Icon
      aria-hidden
      strokeWidth={strokeWidth}
      style={style}
      className={cn('inline-block h-[1em] w-[1em] shrink-0 align-[-0.125em]', className)}
    />
  )
}
